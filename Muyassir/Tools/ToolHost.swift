import SwiftUI

/// Maps every tool id in the registry to its screen.
struct ToolHost: View {
    let tool: Tool
    var body: some View { screen() }
    // AnyView keeps the 74-way switch cheap to type-check.
    private func screen() -> AnyView {
        switch tool.id {
        case "pdf_word": return AnyView(PdfToWord(tool: tool))
        case "word_pdf": return AnyView(WordToPdf(tool: tool))
        case "pdf_excel": return AnyView(PdfToExcel(tool: tool))
        case "excel_pdf": return AnyView(ExcelToPdf(tool: tool))
        case "pdf_ppt": return AnyView(PdfToPpt(tool: tool))
        case "ppt_pdf": return AnyView(PptToPdf(tool: tool))
        case "pdf_img": return AnyView(PdfToImages(tool: tool))
        case "img_pdf": return AnyView(ImagesToPdf(tool: tool))
        case "pdf_merge": return AnyView(PdfMerge(tool: tool))
        case "pdf_split": return AnyView(PdfSplit(tool: tool))
        case "pdf_compress": return AnyView(PdfCompress(tool: tool))
        case "pdf_reorder": return AnyView(PdfPages(tool: tool, mode: .reorder))
        case "pdf_delete": return AnyView(PdfPages(tool: tool, mode: .delete))
        case "pdf_extract": return AnyView(PdfPages(tool: tool, mode: .extract))
        case "pdf_rotate": return AnyView(PdfPages(tool: tool, mode: .rotate))
        case "ocr": return AnyView(OcrTool(tool: tool))
        case "scan": return AnyView(ScanTool(tool: tool))
        case "pdf_protect": return AnyView(PdfProtect(tool: tool))
        case "pdf_unlock": return AnyView(PdfUnlock(tool: tool))
        case "zip": return AnyView(ZipTool(tool: tool))
        case "unzip": return AnyView(UnzipTool(tool: tool))
        case "img_convert": return AnyView(ImgConvert(tool: tool))
        case "img_compress": return AnyView(ImgCompress(tool: tool))
        case "img_resize": return AnyView(ImgResize(tool: tool))
        case "img_crop": return AnyView(ImgCrop(tool: tool))
        case "img_rotate": return AnyView(ImgRotate(tool: tool))
        case "img_enhance": return AnyView(ImgEnhance(tool: tool))
        case "img_bg": return AnyView(ImgBackground(tool: tool))
        case "img_batch": return AnyView(ImgBatch(tool: tool))
        case "id_photo": return AnyView(IdPhoto(tool: tool))
        case "gpa": return AnyView(GpaTool(tool: tool))
        case "percent": return AnyView(PercentTool(tool: tool))
        case "timetable": return AnyView(TimetableTool(tool: tool))
        case "exams": return AnyView(ExamsTool(tool: tool))
        case "homework": return AnyView(HomeworkTool(tool: tool))
        case "attendance": return AnyView(AttendanceTool(tool: tool))
        case "quiz_maker": return AnyView(QuizMaker(tool: tool))
        case "worksheet": return AnyView(WorksheetTool(tool: tool))
        case "flashcards": return AnyView(FlashcardsTool(tool: tool))
        case "study_timer": return AnyView(StudyTimer(tool: tool))
        case "certificate": return AnyView(CertificateTool(tool: tool))
        case "vat": return AnyView(VatTool(tool: tool))
        case "zakat": return AnyView(ZakatTool(tool: tool))
        case "overtime": return AnyView(OvertimeTool(tool: tool))
        case "electricity": return AnyView(ElectricityTool(tool: tool))
        case "date_diff": return AnyView(DateDiffTool(tool: tool))
        case "translate": return AnyView(TranslateTool(tool: tool))
        case "summarize": return AnyView(SummarizeTool(tool: tool))
        case "quiz_gen": return AnyView(QuizGenTool(tool: tool))
        case "read_aloud": return AnyView(ReadAloudTool(tool: tool))
        case "pdf_edit": return AnyView(PdfEditTool(tool: tool))
        case "grades": return AnyView(GradesTool(tool: tool))
        case "salary": return AnyView(SalaryTool(tool: tool))
        case "eos": return AnyView(EosTool(tool: tool))
        case "leave": return AnyView(LeaveTool(tool: tool))
        case "finance": return AnyView(FinanceTool(tool: tool))
        case "discount": return AnyView(DiscountTool(tool: tool))
        case "hijri": return AnyView(HijriTool(tool: tool))
        case "gov_dir": return AnyView(GovDirectory(tool: tool))
        case "emergency": return AnyView(EmergencyTool(tool: tool))
        case "documents": return AnyView(DocumentsTool(tool: tool))
        case "notes": return AnyView(NotesTool(tool: tool))
        case "tasks": return AnyView(TasksTool(tool: tool))
        case "calendar": return AnyView(CalendarTool(tool: tool))
        case "reminders": return AnyView(RemindersTool(tool: tool))
        case "budget": return AnyView(BudgetTool(tool: tool))
        case "expenses": return AnyView(ExpensesTool(tool: tool))
        case "cv": return AnyView(CvTool(tool: tool))
        case "invoice": return AnyView(InvoiceTool(tool: tool))
        case "quote": return AnyView(QuoteTool(tool: tool))
        case "letter": return AnyView(LetterTool(tool: tool))
        case "sign_pdf": return AnyView(SignPdfTool(tool: tool))
        case "text_pdf": return AnyView(TextPdfTool(tool: tool))
        case "scientific": return AnyView(ScientificCalc(tool: tool))
        case "units": return AnyView(UnitsTool(tool: tool))
        case "currency": return AnyView(CurrencyTool(tool: tool))
        case "area_volume": return AnyView(AreaVolume(tool: tool))
        case "qr_make": return AnyView(QrMake(tool: tool))
        case "qr_read": return AnyView(QrRead(tool: tool))
        case "text_compare": return AnyView(TextCompare(tool: tool))
        case "word_count": return AnyView(WordCount(tool: tool))
        case "dedupe": return AnyView(Dedupe(tool: tool))
        case "tts": return AnyView(TtsTool(tool: tool))
        case "stt": return AnyView(SttTool(tool: tool))
        default: return AnyView(EmptyStateView(icon: "questionmark", title: "أداة غير معروفة", text: tool.id))
        }
    }
}
